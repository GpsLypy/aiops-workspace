import { chromium } from 'playwright';
import express from 'express';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createApplication } from '../server/app.mjs';
import { listen } from '../tests/fixtures.mjs';
import { sendResponsesSse } from '../tests/responses-fixture.mjs';

const output = resolve('test-results/reasoning-effort'); mkdirSync(output, { recursive: true });
const dir = mkdtempSync(join(tmpdir(), 'aiops-effort-browser-'));
const application = createApplication({ dataDir: dir, scheduler: false });
const http = await listen(application.app);
const model = express(); model.use(express.json());
const requests = [], checks = [], errors = [];
let release = () => {}, held = Promise.resolve();
model.post('/v1/responses', async (req, res) => {
  requests.push(req.body);
  await held;
  const review = req.body.input[0].content.startsWith('independent-evidence-review');
  sendResponsesSse(res, { status: 'completed', output: [{ type: 'message', role: 'assistant', content: [{ type: 'output_text', text: review ? '{"verdict":"pass","reasons":[]}' : '这是强度设置的受控回答。' }] }], usage: { total_tokens: 15 } });
});
const upstream = await listen(model);
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(http.url);
  await page.locator('input[name=username]').fill('effort-admin');
  await page.locator('input[name=name]').fill('强度验收');
  await page.locator('input[name=password]').fill('effort-browser-test-password');
  await page.getByRole('button', { name: '创建管理员并进入' }).click();
  await page.getByRole('button', { name: '当前用户', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '工作空间设置' });
  await settings.getByLabel('API Base URL').fill(upstream.url + '/v1');
  await settings.getByLabel('模型名称').fill('effort-fixture');
  await settings.locator('input[name=temperature]').fill('');
  await settings.getByLabel('默认问答强度').selectOption('medium');
  await settings.getByRole('button', { name: '保存模型配置', exact: true }).click();
  await settings.getByRole('status').filter({ hasText: '模型配置已保存' }).waitFor();
  await settings.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.goto(http.url + '/#chat');
  const trigger = () => page.getByRole('button', { name: /^问答强度：/ });
  await trigger().filter({ hasText: '均衡' }).waitFor();
  await trigger().focus(); await page.keyboard.press('Enter');
  const menu = page.getByRole('menu', { name: '问答强度', exact: true });
  assert.equal(await menu.getByRole('menuitemradio', { name: /均衡/ }).getAttribute('aria-checked'), 'true');
  assert.match(await menu.innerText(), /系统默认/);
  await page.keyboard.press('ArrowUp'); await page.keyboard.press('Enter');
  assert.match(await trigger().innerText(), /快速/);
  assert.equal(await trigger().evaluate(el => el === document.activeElement), true);
  checks.push('administrator default saved; three descriptive choices, selected/default marks, keyboard selection and focus restoration');
  const send = async text => {
    await page.getByRole('textbox', { name: '输入你的问题' }).fill(text);
    await page.getByRole('button', { name: '发送消息', exact: true }).click();
  };
  held = new Promise(resolve => { release = resolve; });
  await send('快速强度验收');
  await page.waitForFunction(() => document.querySelector('.effort-trigger')?.disabled);
  assert.equal(await trigger().isDisabled(), true);
  release();
  await page.waitForFunction(() => !document.querySelector('.effort-trigger')?.disabled);
  assert.deepEqual(requests.at(-1).reasoning, { effort: 'low' });
  assert.match(await page.locator('.message.assistant').last().innerText(), /快速/);
  await page.reload();
  await trigger().filter({ hasText: '均衡' }).waitFor();
  await page.getByRole('button', { name: '快速强度验收', exact: true }).click();
  await page.locator('.message.assistant').filter({ hasText: '快速' }).waitFor();
  checks.push('actual low parameter, locked while running, persisted message effort; refresh restores global default and retains history effort');
  await trigger().click();
  await menu.getByRole('menuitemradio', { name: /深度/ }).click();
  await page.getByRole('switch', { name: '独立复核' }).click();
  const before = requests.length;
  await send('深度独立复核验收');
  await page.waitForFunction(() => !document.querySelector('.effort-trigger')?.disabled);
  await page.locator('.agent-review').filter({ hasText: '通过' }).waitFor();
  assert.equal(requests.length - before, 2);
  for (const body of requests.slice(before)) assert.deepEqual(body.reasoning, { effort: 'high' });
  assert.equal(application.store.setting('model').model_reasoning_effort, 'medium');
  checks.push('high effort reaches analysis and independent reviewer; conversation override does not change system settings');
  await trigger().click(); await menu.getByRole('menuitem', { name: /使用服务商默认/ }).click();
  await page.getByRole('switch', { name: '独立复核' }).click();
  await send('服务商默认验收');
  await page.waitForFunction(() => !document.querySelector('.effort-trigger')?.disabled);
  assert.equal(requests.at(-1).reasoning, undefined);
  await trigger().click(); await menu.getByRole('menuitem', { name: /使用系统默认/ }).click();
  assert.match(await trigger().innerText(), /均衡/);
  checks.push('provider default omits reasoning; reset returns to configured medium');
  for (const width of [1280, 320]) {
    await page.setViewportSize({ width, height: width === 320 ? 568 : 900 });
    await trigger().click();
    const bounds = await menu.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: join(output, `menu-${width}.png`), fullPage: true });
    await page.keyboard.press('Escape');
    assert.equal(await trigger().evaluate(el => el === document.activeElement), true);
  }
  await trigger().click(); await page.locator('.header-title').click();
  assert.equal(await menu.count(), 0);
  checks.push('desktop and 320px menu stays in viewport with no horizontal overflow; Escape and outside click close');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: '当前用户', exact: true }).click();
  await settings.getByLabel('默认问答强度').selectOption('');
  await settings.getByRole('button', { name: '保存模型配置', exact: true }).click();
  await settings.getByRole('status').filter({ hasText: '模型配置已保存' }).waitFor();
  await settings.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.reload();
  await trigger().filter({ hasText: '选择强度' }).waitFor();
  assert.equal(application.store.setting('model').model_reasoning_effort, null);
  checks.push('provider default survives settings save and reload');
  assert.deepEqual(errors, []);
  writeFileSync(join(output, 'browser-report.json'), JSON.stringify({ checkedAt: new Date().toISOString(), mode: 'fixture', checks, requests: requests.length, errors }, null, 2) + '\n');
  console.log(JSON.stringify({ checks, requests: requests.length, errors }));
} finally {
  release(); await browser.close(); await http.close(); await application.close(); await upstream.close(); rmSync(dir, { recursive: true, force: true });
}
