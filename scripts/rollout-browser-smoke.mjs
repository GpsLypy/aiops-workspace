import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { runtimeFixture } from '../tests/runtime-fixture.mjs';

const h = await runtimeFixture({ runtime: 'agentscope' });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
const output = resolve('test-results/rollout'); mkdirSync(output, { recursive: true });
const errors = [], results = [];
try {
  const created = (await h.request('/resources', { kind: 'agents', name: 'DTS 验收增强', body: '只基于本轮证据回答。' })).data;
  await h.request(`/resources/${created.id}/publish`, { revision: created.revision });
  const page = await browser.newPage({ viewport: { width: 1360, height: 1000 } }); page.on('pageerror', e => errors.push(e.message));
  await page.goto(h.url);
  await page.locator('input[name=username]').fill('admin'); await page.locator('input[name=password]').fill('runtime-test-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  const open = async () => { await page.getByRole('button', { name: '当前用户', exact: true }).click(); await page.getByRole('button', { name: 'Agent 增强', exact: true }).click(); };
  await open();
  const panel = page.getByRole('region', { name: 'Agent 增强配置' });
  await panel.getByText('使用部署增强配置', { exact: true }).waitFor();
  await panel.getByText('所有对话统一使用 AgentScope。', { exact: false }).waitFor();
  assert.equal(await panel.getByLabel('通用 Agent（未选择子领域的对话）', { exact: true }).isEnabled(), true);
  await panel.getByLabel('DTS 验收增强', { exact: true }).check();
  await panel.getByLabel('历史上下文', { exact: true }).selectOption('budgeted');
  await panel.getByLabel('知识片段', { exact: true }).selectOption('diverse');
  await panel.getByLabel('生成本轮证据报告').check();
  await panel.getByRole('button', { name: '保存草稿', exact: true }).click();
  await panel.getByRole('status').filter({ hasText: '草稿已保存' }).waitFor();
  await page.reload(); await open();
  assert.equal(await panel.getByLabel('DTS 验收增强', { exact: true }).isChecked(), true);
  assert.equal(await panel.getByLabel('历史上下文').inputValue(), 'budgeted');
  await panel.getByRole('button', { name: '预检已保存草稿' }).click();
  await panel.getByRole('status').filter({ hasText: '本地 SDK 预检通过' }).waitFor();
  await panel.getByRole('button', { name: '启用增强', exact: true }).focus(); await page.keyboard.press('Enter');
  await panel.getByRole('status').filter({ hasText: '增强已启用' }).waitFor();
  const active = await h.request('/chat', { text: '验证增强', agentId: created.id });
  assert.equal(active.data.metadata.runtimePolicy.runtime, 'agentscope'); assert.equal(active.data.metadata.runtimePolicy.contextMode, 'budgeted');
  assert.equal(active.data.metadata.runtimePolicy.matched, true); assert.equal(active.data.metadata.runtimePolicy.retrievalMode, 'diverse'); assert.equal(active.data.metadata.runtimePolicy.evidenceReports, true);
  const outside = await h.request('/chat', { text: '通用 Agent 未纳入增强范围' });
  assert.equal(outside.data.metadata.runtimePolicy.runtime, 'agentscope'); assert.equal(outside.data.metadata.runtimePolicy.evidenceReports, false);
  assert.equal(outside.data.metadata.runtimePolicy.matched, false); assert.equal(outside.data.metadata.runtimePolicy.contextMode, 'recent'); assert.equal(outside.data.metadata.runtimePolicy.retrievalMode, 'ranked');
  results.push('save/reload, local SDK preflight, keyboard activation, scoped enhancements and AgentScope baseline outside scope');
  await page.screenshot({ path: resolve(output, 'rollout-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 680 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await panel.evaluate(e => e.scrollWidth <= e.clientWidth), true);
  await page.screenshot({ path: resolve(output, 'rollout-mobile.png'), fullPage: true });
  await panel.getByRole('button', { name: '暂停增强', exact: true }).click();
  await panel.getByRole('status').filter({ hasText: '增强已暂停，后续对话继续使用 AgentScope 基础配置' }).waitFor();
  const paused = await h.request('/chat', { text: '暂停后检查', agentId: created.id });
  assert.equal(paused.data.metadata.runtimePolicy.runtime, 'agentscope'); assert.equal(paused.data.metadata.runtimePolicy.mode, 'paused');
  assert.equal(paused.data.metadata.runtimePolicy.contextMode, 'recent'); assert.equal(paused.data.metadata.runtimePolicy.retrievalMode, 'ranked'); assert.equal(paused.data.metadata.runtimePolicy.evidenceReports, false);
  await page.reload(); await open(); await panel.getByText('增强已暂停 · AgentScope 基础配置', { exact: true }).waitFor();
  let current = (await h.request('/settings/agent-rollout')).data;
  assert.equal(current.runtimeRequired, true); assert.equal(current.deployment.runtime, 'agentscope'); assert.equal('agentIds' in current.deployment, false);
  await h.request('/settings/agent-rollout', { revision: current.revision, draft: { ...current.draft, retrievalMode: 'ranked' } }, 'PUT');
  await panel.getByLabel('生成本轮证据报告').uncheck();
  await panel.getByRole('button', { name: '保存草稿', exact: true }).click();
  await panel.getByRole('alert').filter({ hasText: '增强配置已被修改' }).waitFor();
  await panel.getByRole('button', { name: '重新读取配置' }).click();
  await panel.getByRole('status').filter({ hasText: '重新读取' }).waitFor();
  assert.equal(await panel.getByLabel('知识片段').inputValue(), 'ranked');
  results.push('320px no overflow, pause/reload, next run AgentScope baseline, conflicting edit rejected and refreshed');
  await page.keyboard.press('Escape'); assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual(errors, []);
  writeFileSync(resolve(output, 'browser-report.json'), JSON.stringify({ measuredAt: new Date().toISOString(), results, errors, productionUsed: false }, null, 2) + '\n');
  console.log(JSON.stringify({ results, errors, output }, null, 2));
} finally { await browser.close(); await h.close(); }
